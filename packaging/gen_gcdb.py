"""Regenerate betterbluetooth/inputmap/gcdb_windows.py from SDL_GameControllerDB.

Usage: python packaging/gen_gcdb.py path/to/gamecontrollerdb.txt

Source: https://github.com/mdqinc/SDL_GameControllerDB (zlib license).
Only Windows entries with a standard USB/Bluetooth GUID (bus 0x03 / 0x05,
VID + PID encoded) are kept, keyed by "vvvv:pppp".
"""
from __future__ import annotations

import sys
from pathlib import Path

KEEP = {
    "a", "b", "x", "y", "back", "start", "guide",
    "leftshoulder", "rightshoulder", "leftstick", "rightstick",
    "lefttrigger", "righttrigger",
    "dpup", "dpdown", "dpleft", "dpright",
    "leftx", "lefty", "rightx", "righty",
    "misc1", "paddle1", "paddle2", "paddle3", "paddle4",
}
OUT = Path(__file__).resolve().parents[1] / "betterbluetooth" / "inputmap" / "gcdb_windows.py"


def parse(src: str) -> dict[str, tuple[str, str]]:
    out: dict[str, tuple[str, str]] = {}
    for line in src.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "platform:Windows" not in line:
            continue
        parts = line.rstrip(",").split(",")
        guid, name = parts[0].lower(), parts[1]
        if len(guid) != 32 or guid[:8] not in ("03000000", "05000000"):
            continue
        if guid[12:16] != "0000" or guid[20:24] != "0000":
            continue
        vid = guid[10:12] + guid[8:10]
        pid = guid[18:20] + guid[16:18]
        key = f"{vid}:{pid}"
        if key in out:
            continue
        fields = []
        for p in parts[2:]:
            k, _, v = p.partition(":")
            if k.lstrip("+-") in KEEP:
                fields.append(f"{k}:{v}")
        out[key] = (name, ",".join(fields))
    return out


def main() -> None:
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    table = parse(src)
    lines = [
        '"""Windows button/axis mappings from SDL_GameControllerDB (zlib license).',
        "",
        "Generated by packaging/gen_gcdb.py — do not edit by hand.",
        'Key: "vvvv:pppp" (hex VID:PID) → (name, SDL mapping fields).',
        '"""',
        "",
        "MAPPINGS: dict[str, tuple[str, str]] = {",
    ]
    for key in sorted(table):
        name, fields = table[key]
        lines.append(f"    {key!r}: ({name!r}, {fields!r}),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(table)} entries → {OUT}")


if __name__ == "__main__":
    main()
